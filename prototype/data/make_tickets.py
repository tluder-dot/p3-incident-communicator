def main(out_path: str) -> None:
    rows = [
        (text, cat, lang)
        for cat, by_lang in DATA.items()
        for lang, texts in by_lang.items()
        for text in texts
    ]
    texts = [r[0] for r in rows]
    assert len(texts) == len(set(texts)), "duplicate texts"
    random.Random(20261117).shuffle(rows)
    with open(out_path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, quoting=csv.QUOTE_MINIMAL, lineterminator="\n")
        w.writerow(["id", "text", "category", "language", "origin"])
        for i, (text, cat, lang) in enumerate(rows, start=1):
            w.writerow([f"T{i:04d}", text, cat, lang, ORIGIN])
    print(f"wrote {len(rows)} rows to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1])
